"""Build the profile form; Panel keeps the controls, draft and signal ownership."""
from pathlib import Path

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QComboBox, QFrame, QGridLayout, QHBoxLayout, QLabel,
                               QLineEdit, QPlainTextEdit, QScrollArea, QSizePolicy,
                               QVBoxLayout, QWidget)
from ddm import theme
from ddm.ui import ActionButton, DisclosureButton, HintLabel, SettingsSurface, SelectControl
from .configuration import USER_AGENTS


def build_profile_editor(panel, options):
    editor = QWidget()
    layout = QVBoxLayout(editor)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(10)
    panel.back_to_profiles = ActionButton('配置列表')
    panel.back_to_profiles.clicked.connect(lambda: panel.configuration_views.setCurrentIndex(0))
    layout.addWidget(panel.back_to_profiles, 0, Qt.AlignLeft)
    scroll = panel.editor_scroll = QScrollArea()
    scroll.setFrameShape(QFrame.NoFrame)
    scroll.setWidgetResizable(True)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    content = QWidget()
    content.setObjectName('ProxyEditor')
    outer = QVBoxLayout(content)
    outer.setContentsMargins(0, 0, 0, 0)
    outer.setSpacing(10)
    panel.editor_card = SettingsSurface()
    panel.editor_card.setObjectName('ProxyCard')
    form = QGridLayout(panel.editor_card)
    form.setContentsMargins(14, 12, 14, 12)
    form.setHorizontalSpacing(12)
    form.setVerticalSpacing(12)
    form.setColumnMinimumWidth(0, 80)
    form.setColumnStretch(1, 1)
    outer.addWidget(panel.editor_card)
    panel.profile_name = QLineEdit(options.profile_name if options.profile else '')
    panel.profile_name.setPlaceholderText('自动识别服务商（可选）')
    panel.profile_name.setMinimumWidth(0)
    panel.profile_name.setFixedHeight(theme.CONTROL_HEIGHT)
    panel.profile_name.setToolTip('留空时读取订阅名称，未提供时显示订阅域名')
    panel.source = SelectControl()
    panel.source.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Fixed)
    panel.source.setMinimumWidth(0)
    panel.source.setMinimumContentsLength(6)
    for name, value in [('订阅地址', 'url'), ('本地 Clash／Mihomo 配置', 'file'), ('节点链接', 'nodes')]:
        panel.source.addItem(name, value)
    panel.source.setCurrentIndex(panel.source.findData(options.source))
    for row, title, control in ((0, '配置名称', panel.profile_name), (1, '导入方式', panel.source)):
        label = QLabel(title)
        label.setBuddy(control)
        form.addWidget(label, row, 0)
        form.addWidget(control, row, 1)
    panel.location_label = QLabel('订阅地址')
    panel.location = QLineEdit(options.profile if options.source != 'nodes' else '')
    panel.location.setMinimumWidth(0)
    panel.location.setFixedHeight(theme.CONTROL_HEIGHT)
    panel.location.returnPressed.connect(panel._confirm_import)
    panel.location_label.setBuddy(panel.location)
    panel.location_row = QWidget()
    location = QHBoxLayout(panel.location_row)
    location.setContentsMargins(0, 0, 0, 0)
    location.setSpacing(8)
    location.addWidget(panel.location, 1)
    panel.browse_profile = ActionButton('选择文件…')
    panel.browse_profile.clicked.connect(panel._profile_file)
    location.addWidget(panel.browse_profile)
    form.addWidget(panel.location_label, 2, 0)
    form.addWidget(panel.location_row, 2, 1)
    panel.profile_label = QLabel('节点链接')
    panel.profile = QPlainTextEdit(options.profile if options.source == 'nodes' else '')
    panel.profile.setFixedHeight(100)
    panel.profile_label.setBuddy(panel.profile)
    form.addWidget(panel.profile_label, 3, 0, Qt.AlignTop)
    form.addWidget(panel.profile, 3, 1)
    panel.compatibility = DisclosureButton()
    panel.compatibility.setText('订阅兼容设置')
    outer.addWidget(panel.compatibility)
    panel.agent_area = SettingsSurface()
    agent_box = QVBoxLayout(panel.agent_area)
    agent_box.setContentsMargins(14, 12, 14, 12)
    agent_box.setSpacing(8)
    agent_form = QGridLayout()
    agent_form.setHorizontalSpacing(12)
    agent_form.setColumnMinimumWidth(0, 80)
    agent_form.setColumnStretch(1, 1)
    panel.agent_label = QLabel('客户端标识')
    panel.agent = QComboBox()
    panel.agent.setEditable(True)
    panel.agent.setAccessibleName('订阅格式／User-Agent')
    panel.agent.lineEdit().setPlaceholderText('选择或输入自定义 User-Agent')
    panel.agent.setMinimumWidth(0)
    panel.agent.setFixedHeight(theme.CONTROL_HEIGHT)
    panel.agent.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Fixed)
    for label, value in USER_AGENTS:
        panel.agent.addItem(label, value)
    panel.agent_label.setBuddy(panel.agent)
    panel._set_user_agent(options.user_agent)
    agent_form.addWidget(panel.agent_label, 0, 0)
    agent_form.addWidget(panel.agent, 0, 1)
    agent_box.addLayout(agent_form)
    agent_box.addWidget(HintLabel('仅在服务商要求时修改。通常保持 Mihomo，也支持自定义 User-Agent。'))
    panel.compatibility.toggled.connect(panel._compatibility)
    outer.addWidget(panel.agent_area)
    panel.advanced = DisclosureButton()
    panel.advanced.setText('内核设置')
    outer.addWidget(panel.advanced)
    panel.runtime = SettingsSurface()
    runtime = QVBoxLayout(panel.runtime)
    runtime.setContentsMargins(14, 12, 14, 12)
    runtime.setSpacing(8)
    runtime.addWidget(HintLabel('首次启用会自动准备内核，也可选择本机已有的 Mihomo。'))
    panel.core = QLineEdit(options.core)
    panel.core.setMinimumWidth(0)
    panel.core.setFixedHeight(theme.CONTROL_HEIGHT)
    panel.core.setAccessibleName('内核程序路径')
    runtime.addWidget(panel.core)
    actions = QHBoxLayout()
    choose = ActionButton('选择内核…')
    choose.clicked.connect(panel._core_file)
    actions.addWidget(choose)
    panel.prepare = ActionButton('准备内核')
    panel.prepare.clicked.connect(panel.prepareRequested)
    actions.addWidget(panel.prepare)
    actions.addStretch()
    runtime.addLayout(actions)
    panel.advanced.setChecked(not Path(options.core).is_file())
    panel.advanced.toggled.connect(panel._advanced)
    panel._advanced(panel.advanced.isChecked())
    outer.addWidget(panel.runtime)
    outer.addStretch()
    scroll.setWidget(content)
    layout.addWidget(scroll, 1)
    panel.import_status = HintLabel('填写地址后导入，成功后保存配置并启用代理。')
    layout.addWidget(panel.import_status)
    panel.import_button = ActionButton()
    panel.import_button.setObjectName('PrimaryButton')
    panel.import_button.clicked.connect(panel._confirm_import)
    layout.addWidget(panel.import_button, 0, Qt.AlignRight)
    return editor
